void Require(bool condition, const char* why) { if (!condition) throw std::runtime_error(why); }
std::vector<unsigned char> Read(const fs::path& p) {
    FileUtil::IOFile file(p.string(), "rb"); Require(bool(file), "missing expected artifact");
    std::vector<unsigned char> bytes(file.GetSize());
    Require(file.ReadBytes(bytes.data(), bytes.size()) == bytes.size(), "short artifact read");
    return bytes;
}
void Write(const fs::path& p, const std::vector<unsigned char>& bytes) {
    FileUtil::IOFile file(p.string(), "wb"); Require(bool(file), "artifact write open");
    Require(file.WriteBytes(bytes.data(), bytes.size()) == bytes.size() && file.Flush(), "artifact write");
}
fs::path OnlyModule(const fs::path& root) {
    for (const auto& p : fs::directory_iterator(root)) if (p.path().extension() == ".spv") return p.path();
    throw std::runtime_error("no persisted module");
}
void NoTemporary(const fs::path& root) {
    for (const auto& p : fs::directory_iterator(root))
        Require(p.path().extension() != ".tmp", "temporary file survived completed operation");
}
