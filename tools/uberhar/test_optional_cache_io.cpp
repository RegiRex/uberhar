bool Rename(const std::string& from, const std::string& to) {
    ++renames;
    if (!from.ends_with(".tmp")) throw std::runtime_error("replacement lacked temporary file");
    if (fail_rename) return false;
    return std::rename(from.c_str(), to.c_str()) == 0;
}
bool ForeachDirectoryEntry(u64*, const std::string& path,
                          const std::function<bool(u64*, const std::string&, const std::string&)>& visit) {
    for (const auto& entry : fs::directory_iterator(path))
        if (!visit(nullptr, path, entry.path().filename().string())) return false;
    return true;
}
class IOFile {
public:
    IOFile(const std::string& path, const char* mode) : handle(std::fopen(path.c_str(), mode)) {}
    ~IOFile() { Close(); }
    IOFile(const IOFile&) = delete;
    explicit operator bool() const { return handle != nullptr; }
    u64 GetSize() const {
        const auto pos = std::ftell(handle); std::fseek(handle, 0, SEEK_END);
        const auto size = std::ftell(handle); std::fseek(handle, pos, SEEK_SET);
        return static_cast<u64>(size);
    }
    std::size_t ReadBytes(void* data, std::size_t size) { return std::fread(data, 1, size, handle); }
    std::size_t WriteBytes(const void* data, std::size_t size) { return std::fwrite(data, 1, size, handle); }
    bool Flush() { return std::fflush(handle) == 0; }
    void Close() { if (handle) { std::fclose(handle); handle = nullptr; } }
private:
    std::FILE* handle{};
};
